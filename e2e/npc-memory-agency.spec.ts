import { test, expect } from '@playwright/test';
const qaURL=process.env.CAMP_AGENCY_URL;
test('desktop persistent memory, collective negotiation and independent cognition settings',async({page,context},info)=>{
  test.skip(!qaURL,'需要独立 QA 服务，避免操作现有玩家进度');
  await context.addCookies([{name:'campmind-player',value:'00000000-0000-4000-8000-000000000001',url:qaURL!}]);
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(qaURL!,{waitUntil:'domcontentloaded'});await expect(page.getByRole('button',{name:/游戏设置/}).first()).toBeVisible({timeout:30000});
  await page.getByRole('button',{name:/游戏设置/}).first().click();
  await expect(page.getByRole('region',{name:'NPC 记忆与自主行为'})).toBeVisible();
  await expect(page.getByRole('region',{name:'NPC 记忆与自主行为'}).getByText(/认知已默认开启/)).toBeVisible();
  await expect(page.getByRole('region',{name:'NPC 记忆与自主行为'}).locator('select')).toHaveCount(0);
  await page.screenshot({path:info.outputPath('npc-agency-settings.png')});
  await page.getByRole('button',{name:'返回游戏',exact:true}).click();
  const buttons=await page.getByRole('button').allTextContents();
  // Locator is confirmed against actual labels during the QA run.
  const companion=page.getByRole('button',{name:'选择林枫',exact:true});
  await expect(companion,JSON.stringify(buttons)).toBeVisible();await companion.click();
  await expect(companion).toHaveAttribute('aria-pressed','true');
  const options=page.getByRole('button',{name:'营地选项',exact:true});if(await options.isVisible())await options.click();
  const talk=page.getByRole('button',{name:'主动聊聊',exact:true});await expect(talk).toBeVisible();await talk.click();
  await expect(page.getByRole('region',{name:'林枫的持续记忆'})).toBeVisible();
  await page.getByText('持续记忆与个人看法',{exact:false}).click();
  await page.getByRole('button',{name:'加载历史经历',exact:true}).click();
  await expect(page.getByRole('region',{name:'林枫的持续记忆'}).getByText('听到的发言',{exact:true}).first()).toBeVisible();
  await page.screenshot({path:info.outputPath('npc-memory-and-collective.png')});
  const collective=page.getByRole('region',{name:'共同诉求'});
  await expect(collective).toBeVisible();await collective.getByRole('button',{name:'安排休息',exact:true}).first().click();
  await expect(collective.getByText(/等待实际兑现/).first()).toBeVisible();
  await collective.scrollIntoViewIfNeeded();
  await page.screenshot({path:info.outputPath('npc-collective-promise.png')});
  expect(errors).toEqual([]);
});
